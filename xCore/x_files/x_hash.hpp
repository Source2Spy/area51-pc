#ifndef X_HASH_HPP
#define X_HASH_HPP

//==============================================================================
//  INCLUDES
//==============================================================================

#include "x_plus.hpp"
#include "x_types.hpp"

//==============================================================================
//  TYPES
//==============================================================================

struct x_content_id
{
    //------------------------------------------------------------------------------
    //  FUNCTIONS
    //------------------------------------------------------------------------------

    const byte* GetPtr( void ) const;
    byte*       GetPtr( void );
    byte&       operator[]( s32 Index );
    const byte& operator[]( s32 Index ) const;
    xbool       operator==( const x_content_id& B ) const;
    xbool       operator!=( const x_content_id& B ) const;
    xbool       operator<( const x_content_id& B ) const;

    //------------------------------------------------------------------------------
    //  DATA
    //------------------------------------------------------------------------------

    byte Bytes[32];
};

//------------------------------------------------------------------------------

class x_content_hash
{
public:

    //------------------------------------------------------------------------------
    //  FUNCTIONS
    //------------------------------------------------------------------------------

                 x_content_hash( void );
    void         Update        ( const byte* pData, u32 Size );
    x_content_id Finish        ( void ) const;

private:

    //------------------------------------------------------------------------------
    //  DATA
    //------------------------------------------------------------------------------

    u32  m_State[8];
    byte m_Tail[64];
    u64  m_nBytes;
    u32  m_nTailBytes;
};

//==============================================================================
//  FUNCTIONS
//==============================================================================

x_content_id x_HashContent( const byte* pData, u32 Size );

//==============================================================================
//  INLINE FUNCTIONS
//==============================================================================

inline
const byte* x_content_id::GetPtr( void ) const
{
    return Bytes;
}

//==============================================================================

inline
byte* x_content_id::GetPtr( void )
{
    return Bytes;
}

//==============================================================================

inline
byte& x_content_id::operator[]( s32 Index )
{
    return Bytes[Index];
}

//==============================================================================

inline
const byte& x_content_id::operator[]( s32 Index ) const
{
    return Bytes[Index];
}

//==============================================================================

inline
xbool x_content_id::operator==( const x_content_id& B ) const
{
    return x_memcmp( Bytes, B.Bytes, 32 ) == 0;
}

//==============================================================================

inline
xbool x_content_id::operator!=( const x_content_id& B ) const
{
    return !( *this == B );
}

//==============================================================================

inline
xbool x_content_id::operator<( const x_content_id& B ) const
{
    return x_memcmp( Bytes, B.Bytes, 32 ) < 0;
}

//==============================================================================
#endif // X_HASH_HPP
