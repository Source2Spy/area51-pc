#ifndef ECS_BLOCK_HPP
#define ECS_BLOCK_HPP

//==============================================================================
//  INCLUDES
//==============================================================================

#include "x_types.hpp"

//==============================================================================
//  ENUMS
//==============================================================================

enum ecs_block_codec
{
    ECS_BLOCK_RAW  = 0,
    ECS_BLOCK_ZSTD = 2
};

//------------------------------------------------------------------------------

enum ecs_block_limit
{
    ECS_BLOCK_TARGET_SIZE = 256 * 1024,
    ECS_BLOCK_MAX_SIZE    = 16 * 1024 * 1024
};

//==============================================================================
//  CLASSES
//==============================================================================

class ecs_block_context
{
public:

    //------------------------------------------------------------------------------
    //  LIFETIME
    //------------------------------------------------------------------------------

    ecs_block_context( void );
    ~ecs_block_context( void );
    //------------------------------------------------------------------------------
    //  BLOCK OPERATIONS
    //------------------------------------------------------------------------------

    xbool Compress( const byte* pDecoded, u32 DecodedSize, byte* pStored, u32& StoredSize );
    xbool Decode( ecs_block_codec Codec, const byte* pStored, u32 StoredSize, byte* pDecoded, u32 DecodedSize );

private:

    //------------------------------------------------------------------------------
    //  FUNCTIONS
    //------------------------------------------------------------------------------

    ecs_block_context( const ecs_block_context& );
    ecs_block_context& operator=( const ecs_block_context& );

    //------------------------------------------------------------------------------
    //  DATA
    //------------------------------------------------------------------------------

    void* m_pCompression;
    void* m_pDecompression;
};

//==============================================================================
//  FUNCTIONS
//==============================================================================

u32   ecs_CompressBound( u32 DecodedSize );
xbool ecs_CompressBlock( const byte* pDecoded, u32 DecodedSize, byte* pStored, u32& StoredSize );
xbool ecs_DecodeBlock( ecs_block_codec Codec, const byte* pStored, u32 StoredSize, byte* pDecoded, u32 DecodedSize );

//==============================================================================
#endif // ECS_BLOCK_HPP
